// Builds the page the reader's WebView shows (src/reader/web/page) into one
// HTML string, src/reader/web/page.generated.ts, which the app ships.
// Run after changing anything in src/reader/web/page, protocol.ts or
// gestures.ts: `npm run build:page`. A test fails while it's out of date.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = join(ROOT, 'src/reader/web/page');

/** Everything the page is built from, for the up-to-date check. */
export function pageSources() {
  const files = [
    ...readdirSync(PAGE)
      .filter((f) => /\.(ts|css)$/.test(f))
      .map((f) => join(PAGE, f)),
    join(ROOT, 'src/reader/web/protocol.ts'),
    join(ROOT, 'src/reader/gestures.ts'),
  ].sort();
  return files;
}

export function sourceHash() {
  const h = createHash('sha256');
  for (const f of pageSources()) h.update(f.slice(ROOT.length)).update(readFileSync(f));
  return h.digest('hex').slice(0, 16);
}

async function main() {
  const out = await build({
    entryPoints: [join(PAGE, 'main.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    minify: true,
    target: ['chrome80', 'safari15'],
    logLevel: 'warning',
  });
  const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const css = readFileSync(join(PAGE, 'base.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s*\n\s*/g, '');
  const html =
    '<!doctype html><html><head><meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">' +
    `<style>${css}</style><style id="book"></style><style id="marks"></style></head>` +
    `<body><div id="viewport"></div><div id="scroll"></div><script>${js}</script></body></html>`;
  writeFileSync(
    join(ROOT, 'src/reader/web/page.generated.ts'),
    '// Generated by scripts/build-reader-page.mjs from src/reader/web/page. Do not edit.\n' +
      `export const PAGE_SOURCE_HASH = '${sourceHash()}';\n` +
      `export const PAGE_HTML = ${JSON.stringify(html)};\n`,
  );
  console.log(`src/reader/web/page.generated.ts: ${(html.length / 1024).toFixed(1)} KB`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
